# GPIO wiring
CS_GPIO = 8
CLK_GPIO = 11
MOSI_GPIO = 10
MISO_GPIO = 9

NOTIFY_STRUCT = struct.Struct("<HHII")
NOTIFY_SIZE = NOTIFY_STRUCT.size


@dataclass
class Recording:
    time_s: np.ndarray
    signal: np.ndarray
    metadata: dict
    adc: np.ndarray | None = None


@dataclass
class AcquisitionStats:
    samples: int = 0
    bad_transactions: int = 0
    notification_gaps: int = 0


class MCP3008DMA:
    """Precise MCP3008 acquisition with a hardware-timed pigpio waveform.

    One complete MCP3008 transaction is repeated every integer number of
    microseconds. The actual achievable rate is therefore reported as
    1e6 / integer_period_us, rather than silently claiming an exact rate
    that the pigpio microsecond clock cannot represent.
    """

    def __init__(self, channel: int, requested_fs: float, buffer_size: int):
        if not 0 <= channel <= 7:
            raise ValueError("MCP3008 channel must be between 0 and 7.")
        if requested_fs <= 0 or not math.isfinite(requested_fs):
            raise ValueError("Sample rate must be finite and positive.")

        if pigpio is None:
            raise RuntimeError(
                "MCP3008 DMA mode needs pigpio. Install it and run pigpiod."
            )

        self.pigpio = pigpio
        self.channel = channel
        self.requested_fs = float(requested_fs)
        self.period_us = max(1, int(round(1_000_000 / requested_fs)))
        self.actual_fs = 1_000_000.0 / self.period_us
        self.buffer_size = int(buffer_size)

        self.pi = pigpio.pi()
        if not self.pi.connected:
            raise RuntimeError(
                "Cannot connect to pigpio. Start it with: sudo pigpiod -s 1"
            )

        self.adc = np.empty(self.buffer_size, dtype=np.uint16)
        self.tick = np.empty(self.buffer_size, dtype=np.uint32)
        self.sample_index = 0
        self.stats = AcquisitionStats()
        self.transaction_clock = 0
        self.data_value = 0
        self.previous_clk = False
        self.previous_cs = True
        self.expected_sequence = None
        self.running = False

        try:
            self._configure_gpio()
            self.wave_id = self._create_waveform()

            self.notify_handle = self.pi.notify_open()
            if self.notify_handle < 0:
                raise RuntimeError("Unable to open pigpio notification stream.")

            mask = (1 << CS_GPIO) | (1 << CLK_GPIO) | (1 << MISO_GPIO)
            if self.pi.notify_begin(self.notify_handle, mask) != 0:
                raise RuntimeError("Unable to start pigpio notification stream.")

            self.notify_path = f"/dev/pigpio{self.notify_handle}"
            self.notify_fd = os.open(self.notify_path, os.O_RDONLY)
        except Exception:
            self.close()
            raise

    def _configure_gpio(self):
        p = self.pigpio
        self.pi.set_mode(CS_GPIO, p.OUTPUT)
        self.pi.set_mode(CLK_GPIO, p.OUTPUT)
        self.pi.set_mode(MOSI_GPIO, p.OUTPUT)
        self.pi.set_mode(MISO_GPIO, p.INPUT)
        self.pi.write(CS_GPIO, 1)
        self.pi.write(CLK_GPIO, 0)
        self.pi.write(MOSI_GPIO, 0)

    def _create_waveform(self):
        p = self.pigpio
        CS, CLK, MOSI = 1 << CS_GPIO, 1 << CLK_GPIO, 1 << MOSI_GPIO
        half = max(1, int(round(1_000_000 / (2 * 100_000))))
        pulses = [p.pulse(0, CS, 2)]

        command = [1, 1, (self.channel >> 2) & 1,
                   (self.channel >> 1) & 1, self.channel & 1]
        for bit in command:
            pulses.append(p.pulse(MOSI if bit else 0, 0 if bit else MOSI, half))
            pulses.append(p.pulse(CLK, 0, half))
            pulses.append(p.pulse(0, CLK, half))

        # 12 clocks: one null/data-leading clock + ten data bits + final clock.
        for _ in range(12):
            pulses.append(p.pulse(CLK, 0, half))
            pulses.append(p.pulse(0, CLK, half))

        pulses.append(p.pulse(CS, MOSI, 2))
        transaction_us = sum(x.usDelay for x in pulses)
        idle_us = self.period_us - transaction_us
        if idle_us <= 0:
            raise ValueError(
                f"Requested rate {self.requested_fs:g} Hz is too high: "
                f"MCP3008 transaction needs {transaction_us} us."
            )
        pulses.append(p.pulse(0, 0, idle_us))

        self.pi.wave_clear()
        self.pi.wave_add_generic(pulses)
        wave_id = self.pi.wave_create()
        if wave_id < 0:
            raise RuntimeError(f"pigpio waveform creation failed: {wave_id}")
        return wave_id

    def start(self):
        self.running = True
        self.sample_index = 0
        self.stats = AcquisitionStats()
        self.transaction_clock = 0
        self.data_value = 0
        self.previous_clk = False
        self.previous_cs = True
        self.expected_sequence = None

        if self.pi.wave_send_repeat(self.wave_id) <= 0:
            self.running = False
            raise RuntimeError("Could not start DMA waveform.")

    def stop(self):
        if self.running:
            self.running = False
            self.pi.wave_tx_stop()

    def process_notifications(self, duration_seconds: float):
        start = time.monotonic()
        buffer = bytearray()
        while self.running and time.monotonic() - start < duration_seconds:
            data = os.read(self.notify_fd, 8192)
            if not data:
                continue
            buffer.extend(data)
            usable = (len(buffer) // NOTIFY_SIZE) * NOTIFY_SIZE
            if not usable:
                continue

            block = bytes(buffer[:usable])
            del buffer[:usable]
            reports = np.frombuffer(
                block,
                dtype=np.dtype([
                    ("seq", "<u2"), ("flags", "<u2"),
                    ("tick", "<u4"), ("level", "<u4")
                ]),
            )
            for r in reports:
                self._process_report(
                    int(r["seq"]), int(r["flags"]),
                    int(r["tick"]), int(r["level"])
                )

        self.stop()

    def _process_report(self, sequence, flags, tick, level):
        if self.expected_sequence is not None:
            if sequence != ((self.expected_sequence + 1) & 0xFFFF):
                self.stats.notification_gaps += 1
        self.expected_sequence = sequence

        cs = bool(level & (1 << CS_GPIO))
        clk = bool(level & (1 << CLK_GPIO))
        miso = bool(level & (1 << MISO_GPIO))

        if not cs and self.previous_cs:
            self.transaction_clock = 0
            self.data_value = 0

        if cs and not self.previous_cs:
            if self.transaction_clock != 17:
                self.stats.bad_transactions += 1

        if clk and not self.previous_clk and not cs:
            self.transaction_clock += 1
            clock = self.transaction_clock
            if 8 <= clock <= 17:
                self.data_value = (self.data_value << 1) | int(miso)
                if clock == 17:
                    self._store_sample(tick, self.data_value)

        self.previous_clk = clk
        self.previous_cs = cs

    def _store_sample(self, tick, value):
        if self.sample_index >= self.buffer_size:
            self.running = False
            self.pi.wave_tx_stop()
            return
        self.adc[self.sample_index] = value
        self.tick[self.sample_index] = tick
        self.sample_index += 1
        self.stats.samples += 1

    def get_data(self):
        n = self.sample_index
        return self.tick[:n].copy(), self.adc[:n].copy()

    def close(self):
        try:
            self.stop()
        except Exception:
            pass
        try:
            self.pi.notify_pause(self.notify_handle)
        except Exception:
            pass
        try:
            self.pi.notify_close(self.notify_handle)
        except Exception:
            pass
        try:
            os.close(self.notify_fd)
        except Exception:
            pass
        try:
            self.pi.wave_delete(self.wave_id)
        except Exception:
            pass
        try:
            self.pi.wave_clear()
        except Exception:
            pass
        try:
            self.pi.stop()
        except Exception:
            pass


def write_json(path: Path, values: dict):
    path.write_text(
        json.dumps(values, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )


def save_raw(recording: Recording, folder: Path):
    adc = recording.adc
    if adc is None:
        adc = np.full(len(recording.signal), np.nan)
    np.savetxt(
        folder / "raw.csv",
        np.column_stack((recording.time_s, recording.signal, adc)),
        delimiter=",",
        header="time_s,raw_signal,raw_adc",
        comments="",
        fmt="%.10g",
    )
    np.savez_compressed(
        folder / "raw.npz",
        time_s=recording.time_s,
        raw_signal=recording.signal,
        raw_adc=adc,
    )


def acquire(args, folder: Path) -> Recording:
    """Acquire on a hardware-defined sample grid; save partial data on Ctrl+C."""
    buffer_size = int(math.ceil(args.duration * args.fs)) + 16
    acq = MCP3008DMA(args.channel, args.fs, buffer_size)

    metadata = dict(
        source="mcp3008",
        units="V at ADC input",
        channel=args.channel,
        vref_v=args.vref,
        requested_duration_s=args.duration,
        target_fs_hz=args.fs,
        actual_sample_period_us=acq.period_us,
        actual_fs_hz=acq.actual_fs,
        timestamp_kind="DMA sample grid; GPIO tick retained for diagnostics",
        spi_clock_hz=100_000,
        clock_source="pigpio DMA waveform",
    )
    write_json(folder / "metadata.json", metadata)

    ticks = np.empty(0, dtype=np.uint32)
    adc = np.empty(0, dtype=np.uint16)
    interrupted = False

    try:
        print(
            f"Recording at {acq.actual_fs:.6f} Hz "
            f"(requested {args.fs:g} Hz); Ctrl+C stops safely.",
            flush=True,
        )
        acq.start()
        try:
            acq.process_notifications(args.duration)
        except KeyboardInterrupt:
            interrupted = True
            acq.stop()
        ticks, adc = acq.get_data()
    finally:
        acq.close()

    if len(adc):
        # The DMA waveform defines the sample spacing. The GPIO tick is retained
        # only as an independent diagnostic; notification latency is not used
        # to create artificial sample jitter.
        t = np.arange(len(adc), dtype=np.float64) / acq.actual_fs
        signal = adc.astype(np.float64) * args.vref / 1023.0
    else:
        t = np.empty(0, dtype=np.float64)
        signal = np.empty(0, dtype=np.float64)

    metadata.update(
        samples=int(len(adc)),
        interrupted=interrupted,
        bad_transactions=acq.stats.bad_transactions,
        notification_gaps=acq.stats.notification_gaps,
        measured_grid_fs_hz=acq.actual_fs,
    )
    if len(ticks):
        metadata["gpio_tick_span_s"] = float(
            ((ticks.astype(np.uint64)[-1] - ticks.astype(np.uint64)[0]) & 0xFFFFFFFF)
            / 1_000_000
        )
    write_json(folder / "metadata.json", metadata)

    # Preserve the v2 incremental raw.csv contract even for a partial run.
    np.savetxt(
        folder / "raw.csv",
        np.column_stack((t, signal, adc)),
        delimiter=",",
        header="time_s,raw_signal,raw_adc",
        comments="",
        fmt="%.10g",
    )
    np.savez_compressed(
        folder / "raw.npz",
        time_s=t, raw_signal=signal, raw_adc=adc,
    )
    return Recording(t, signal, metadata, adc)


def demo(fs, duration, bpm, seed=7):
    t = np.arange(round(duration * fs), dtype=np.float64) / fs
    rng = np.random.default_rng(seed)
    y = 0.05 * np.sin(2 * np.pi * 0.25 * t) + rng.normal(0, 0.012, len(t))
    rr = 60 / bpm
    r_times = np.arange(0.7, duration - 0.5, rr)
    for r in r_times:
        for offset, amplitude, width in [
            (-0.20 * rr, 0.17, 0.025),
            (-0.035, -0.18, 0.009),
            (0, 1.0, 0.010),
            (0.035, -0.25, 0.012),
            (0.30 * rr, 0.30, 0.045),
        ]:
            y += amplitude * np.exp(-0.5 * ((t - r - offset) / width) ** 2)
    return Recording(
        t, y,
        dict(
            source="demo", units="arbitrary units",
            target_fs_hz=fs, requested_duration_s=duration,
            demo_hr_bpm=bpm, seed=seed,
            true_r_times_s=r_times.tolist(),
            timestamp_kind="synthetic uniform grid",
        ),
    )


def load_recording(path: Path, fallback_units: str):
    data = np.genfromtxt(path, delimiter=",", names=True, ndmin=1)
    if data.dtype.names is None or not {"time_s", "raw_signal"}.issubset(data.dtype.names):
        raise ValueError("Input CSV must contain time_s,raw_signal columns.")
    metadata = dict(
        source="file",
        input_file=str(path.resolve()),
        units=fallback_units,
        timestamp_kind="from input CSV",
    )
    sidecar = path.with_name("metadata.json")
    if sidecar.exists():
        prior = json.loads(sidecar.read_text(encoding="utf-8"))
        metadata.update(
            units=prior.get("units", fallback_units),
            original_source=prior.get("original_source", prior.get("source")),
            target_fs_hz=prior.get("target_fs_hz"),
            vref_v=prior.get("vref_v"),
            timestamp_kind=prior.get("timestamp_kind", "from input CSV"),
        )
    adc = data["raw_adc"] if "raw_adc" in data.dtype.names else None
    return Recording(data["time_s"], data["raw_signal"], metadata, adc)


def prepare_signal(recording: Recording, args):
    t, raw = recording.time_s, recording.signal
    if len(t) < 100 or not np.all(np.isfinite(t)) or not np.all(np.isfinite(raw)):
        raise ValueError("Need at least 100 finite samples and finite timestamps.")
    dt = np.diff(t)
    if np.any(dt <= 0):
        raise ValueError("Timestamps must be strictly increasing.")
    span = float(t[-1] - t[0])
    if span < 3:
        raise ValueError("Need at least 3 seconds for ECG analysis.")

    median_dt = float(np.median(dt))
    fs = (len(t) - 1) / span
    jitter = float(np.percentile(np.abs(dt - median_dt), 95) / median_dt)
    warnings = [
        "PQRST markers are algorithmic candidates; inspect the plot before use."
    ]
    timing = dict(
        samples=len(t),
        recorded_span_s=span,
        measured_average_fs_hz=float(fs),
        median_interval_ms=median_dt * 1000,
        interval_p95_jitter_fraction=jitter,
        maximum_interval_ms=float(dt.max() * 1000),
    )

    target = recording.metadata.get("target_fs_hz")
    if target and abs(fs / target - 1) > 0.02:
        warnings.append("Measured average rate differs from target by more than 2%.")
    if jitter > 0.10:
        warnings.append(
            "Timing jitter exceeds 10%; interpolation cannot restore lost detail."
        )
    if dt.max() > max(0.020, 5 * median_dt):
        raise ValueError("Large time gap detected; analysis stopped.")

    if not 0 < args.lowcut < args.highcut < fs / 2:
        raise ValueError("Filter cutoffs must satisfy 0 < lowcut < highcut < fs/2.")

    # Interpolate only for imported/asynchronous recordings. DMA recordings are
    # already uniform, so this is effectively a no-op.
    grid = np.linspace(t[0], t[-1], len(t))
    uniform = np.interp(grid, t, raw)

    sos = butter(4, [args.lowcut, args.highcut], btype="bandpass",
                 fs=fs, output="sos")
    filtered = sosfiltfilt(sos, uniform)

    if args.polarity == "auto":
        center = np.median(filtered)
        positive = np.percentile(filtered, 99.5) - center
        negative = center - np.percentile(filtered, 0.5)
        sign = 1 if positive >= negative else -1
    else:
        sign = 1 if args.polarity == "positive" else -1
    filtered *= sign

    residual = uniform - sosfiltfilt(
        butter(3, args.highcut, fs=fs, output="sos"), uniform
    )
    noise = float(1.4826 * np.median(np.abs(residual - np.median(residual))))

    if recording.adc is not None:
        codes = recording.adc[np.isfinite(recording.adc)]
        if len(codes) and np.mean((codes <= 1) | (codes >= 1022)) > 0.01:
            warnings.append("More than 1% of ADC codes are near a rail.")

    # If DMA reported a transport problem, make it visible rather than silently
    # treating the resulting sequence as pristine.
    for key, message in [
        ("bad_transactions", "MCP3008 transaction errors were observed."),
        ("notification_gaps", "pigpio notification gaps were observed."),
    ]:
        if recording.metadata.get(key, 0):
            warnings.append(message)

    return grid, filtered, float(fs), noise, sign, timing, warnings


def detect_r_peaks(t, y, fs, noise, args):
    """Robust R detection retained from v2, with configurable prominence."""
    median = float(np.median(y))
    amplitude = float(np.percentile(y, 99.5) - median)
    background = float(1.4826 * np.median(np.abs(y - median)))
    empty = np.empty((0, 6))

    if amplitude <= 1e-10 or (
        args.r_prominence is None and amplitude <= 6 * background
    ):
        return empty, ["No sufficiently dominant R peaks relative to filtered background."]

    prominence = (
        args.r_prominence
        if args.r_prominence is not None
        else max(6 * background, 0.45 * amplitude)
    )
    peaks, _ = find_peaks(
        y,
        distance=max(1, int(fs * 60 / args.max_hr)),
        prominence=prominence,
        height=median + 0.45 * amplitude,
    )
    peaks = peaks[
        (t[peaks] >= t[0] + 0.4)
        & (t[peaks] <= t[-1] - 0.5)
    ]
    if not len(peaks):
        return empty, ["No R candidates found; check polarity and prominence."]
    return peaks, []


def local_peak(t, y, fs, left, right, direction, noise, amplitude):
    a, b = np.searchsorted(t, [left, right])
    if b - a < 3:
        return np.nan
    segment = direction * y[a:b]
    peaks, props = find_peaks(
        segment,
        prominence=max(2.5 * noise, 0.02 * amplitude),
    )
    if not len(peaks):
        return np.nan
    return float(t[a + peaks[np.argmax(props["prominences"])]])


def fallback_pqrst(t, y, fs, noise, r_indices):
    """v2-style local extrema fallback when NeuroKit2 is unavailable."""
    amplitude = float(np.percentile(y, 99.5) - np.median(y))
    rows = []
    for i, r in enumerate(r_indices):
        rt = float(t[r])
        prev_rr = rt - t[r_indices[i - 1]] if i else (
            t[r_indices[1]] - rt if len(r_indices) > 1 else 0.8
        )
        next_rr = (
            t[r_indices[i + 1]] - rt
            if i + 1 < len(r_indices) else prev_rr
        )
        rows.append([
            i + 1,
            local_peak(t, y, fs, rt - min(0.32, 0.40 * prev_rr),
                       rt - 0.075, 1, noise, amplitude),
            local_peak(t, y, fs, rt - 0.08, rt - 0.008,
                       -1, noise, amplitude),
            rt,
            local_peak(t, y, fs, rt + 0.008, rt + 0.08,
                       -1, noise, amplitude),
            local_peak(t, y, fs, rt + 0.09,
                       rt + min(0.50, 0.60 * next_rr),
                       1, noise, amplitude),
        ])
    return np.asarray(rows, dtype=float), {}, "scipy-local-extrema"


def neurokit_pqrst(t, y, fs, noise, r_indices):
    """Use NeuroKit DWT for P/Q/S/T peaks and boundaries.

    R peaks are deliberately supplied by our detector rather than
    allowing a second detector to silently replace them. Any NeuroKit failure
    falls back to the deterministic SciPy implementation.
    """
    if nk is None:
        beats, waves, method = fallback_pqrst(t, y, fs, noise, r_indices)
        return beats, waves, method, None

    try:
        rpeaks = {"ECG_R_Peaks": np.asarray(r_indices, dtype=int)}
        _, waves = nk.ecg_delineate(
            y, rpeaks=rpeaks, sampling_rate=fs,
            method="dwt", show=False, check=True,
        )

        def arr(key):
            values = np.asarray(waves.get(key, []), dtype=float)
            out = np.full(len(r_indices), np.nan)
            n = min(len(values), len(out))
            if n:
                finite = np.isfinite(values[:n])
                out[:n][finite] = t[
                    np.clip(values[:n][finite].astype(int), 0, len(t) - 1)
                ]
            return out

        rows = np.column_stack([
            np.arange(1, len(r_indices) + 1),
            arr("ECG_P_Peaks"),
            arr("ECG_Q_Peaks"),
            t[r_indices],
            arr("ECG_S_Peaks"),
            arr("ECG_T_Peaks"),
        ])
        return rows, waves, "neurokit-dwt", None
    except ImportError:
        return None
    except Exception as exc:
        return None, str(exc)


def detect_pqrst(t, y, fs, noise, args):
    r_indices, messages = detect_r_peaks(t, y, fs, noise, args)
    if not len(r_indices):
        return np.empty((0, 6)), {}, "none", messages

    nk_result = neurokit_pqrst(t, y, fs, noise, r_indices)
    if nk_result is not None and nk_result[0] is not None:
        beats, waves, method, _ = nk_result
        return beats, waves, method, messages
    if isinstance(nk_result, tuple) and len(nk_result) == 2 and nk_result[1]:
        messages.append(
            "NeuroKit2 DWT delineation failed; using conservative SciPy fallback: "
            + nk_result[1]
        )
    else:
        messages.append(
            "NeuroKit2 not installed; P/Q/S/T use conservative local-extrema fallback."
        )

    beats, waves, method = fallback_pqrst(t, y, fs, noise, r_indices)
    return beats, waves, method, messages


def analyse(recording: Recording, folder: Path, args):
    t, y, fs, noise, sign, timing, warnings = prepare_signal(recording, args)
    beats, waves, delineation_method, messages = detect_pqrst(
        t, y, fs, noise, args
    )
    warnings.extend(messages)

    if len(beats):
        missing = {
            label: int(np.isnan(beats[:, col]).sum())
            for col, label in [(1, "P"), (2, "Q"), (4, "S"), (5, "T")]
        }
        if any(missing.values()):
            warnings.append(
                "Missing small-wave candidates: "
                + ", ".join(f"{k}={v}" for k, v in missing.items())
                + ". Missing markers do not imply physiological absence."
            )

    rr = np.diff(beats[:, 3]) if len(beats) >= 2 else np.array([])
    accepted = (
        (rr >= 60 / args.max_hr) &
        (rr <= 60 / args.min_hr)
    )
    hr = 60 / rr[accepted] if len(rr) else np.array([])

    if np.any(~accepted):
        warnings.append(
            "Some RR intervals lie outside the configured analysis range; "
            "inspect missed/extra peaks."
        )
    if len(rr) < 3:
        warnings.append(
            "Fewer than three RR intervals: rate estimate is especially uncertain."
        )

    background = float(
        1.4826 * np.median(np.abs(y - np.median(y)))
    )
    peak_amplitude = float(
        np.percentile(y, 99.5) - np.median(y)
    )
    r_prominence = (
        args.r_prominence
        if args.r_prominence is not None
        else max(6 * background, 0.45 * peak_amplitude)
    )

    summary = dict(
        script_version=SCRIPT_VERSION,
        timing=timing,
        r_candidates=len(beats),
        accepted_rr_intervals=int(accepted.sum()),
        excluded_rr_intervals=int((~accepted).sum()),
        median_hr_bpm=float(np.median(hr)) if len(hr) else None,
        mean_instantaneous_hr_bpm=float(np.mean(hr)) if len(hr) else None,
        polarity_multiplier=sign,
        noise_estimate=noise,
        noise_estimate_description=(
            "High-frequency residual scale; used conservatively for fallback P/Q/S/T"
        ),
        r_background_scale=background,
        r_prominence_threshold=float(r_prominence),
        r_height_threshold=float(np.median(y) + 0.45 * peak_amplitude),
        r_threshold_mode=(
            "manual prominence"
            if args.r_prominence is not None else "filtered background"
        ),
        delineation_method=delineation_method,
        method=(
            "0.5–40 Hz bandpass; robust prominence/height R detection; "
            "NeuroKit DWT P/Q/S/T when available"
        ),
        filter_hz=[args.lowcut, args.highcut],
        hr_search_bpm=[args.min_hr, args.max_hr],
        warnings=warnings,
    )

    np.savetxt(
        folder / "filtered.csv",
        np.column_stack((t, y)),
        delimiter=",",
        header="time_s,filtered_oriented_signal",
        comments="",
    )
    np.savetxt(
        folder / "pqrst_candidates.csv",
        beats,
        delimiter=",",
        header="beat,P_time_s,Q_time_s,R_time_s,S_time_s,T_time_s",
        comments="",
    )
    rr_end = beats[1:, 3] if len(beats) >= 2 else np.array([])
    np.savetxt(
        folder / "rr_intervals.csv",
        np.column_stack((
            rr_end, rr, 60 / rr, accepted.astype(int)
        )),
        delimiter=",",
        header="R_time_s,RR_s,instantaneous_bpm,in_configured_range",
        comments="",
    )
    write_json(folder / "analysis.json", summary)
    make_plot(
        recording, t, y, beats, waves, rr_end, rr, accepted,
        folder, args, summary,
    )
    return summary


def _wave_indices(waves, key, n):
    values = np.asarray(waves.get(key, []), dtype=float)
    values = values[np.isfinite(values)]
    if not len(values):
        return np.empty(0, dtype=int)
    return values.astype(int)[
        (values >= 0) & (values < n)
    ]


def make_plot(
    recording, t, y, beats, waves, rr_end, rr, accepted,
    folder, args, summary,
):
    fig, axes = plt.subplots(
        3, 1, figsize=(12, 9), constrained_layout=True
    )
    demo_label = (
        recording.metadata.get("source") == "demo"
        or recording.metadata.get("original_source") == "demo"
    )
    title = "SIMULATED ECG" if demo_label else "ECG lab recording"
    fig.suptitle(
        title + " | PQRST candidates require visual checking",
        fontsize=14,
    )

    end = min(float(t[-1]), float(t[0] + args.plot_seconds))
    axes[0].plot(
        recording.time_s, recording.signal,
        lw=0.8, label="Raw recording",
    )
    axes[0].set(
        ylabel=recording.metadata["units"],
        title="Raw recording (unchanged)",
        xlim=(t[0], end),
    )

    axes[1].plot(t, y, lw=0.9, label="Filtered/oriented ECG")
    wave_definitions = [
        (1, "P", "ECG_P_Peaks"),
        (2, "Q", "ECG_Q_Peaks"),
        (3, "R", None),
        (4, "S", "ECG_S_Peaks"),
        (5, "T", "ECG_T_Peaks"),
    ]
    for col, label, key in wave_definitions:
        if key is None:
            times = beats[:, col] if len(beats) else np.array([])
        else:
            times = beats[:, col] if len(beats) else np.array([])
        times = times[np.isfinite(times)]
        if len(times):
            axes[1].scatter(
                times, np.interp(times, t, y),
                s=24, label=label, zorder=4,
            )

    # DWT boundaries are useful visually, but they are not physiologically meaningful and are not reported in CSV
    for label, key in [
        ("P onset", "ECG_P_Onsets"),
        ("P offset", "ECG_P_Offsets"),
        ("QRS onset", "ECG_R_Onsets"),
        ("QRS offset", "ECG_R_Offsets"),
        ("T onset", "ECG_T_Onsets"),
        ("T offset", "ECG_T_Offsets"),
    ]:
        idx = _wave_indices(waves, key, len(t))
        if len(idx):
            axes[1].scatter(
                t[idx], y[idx], s=15, marker="x",
                label=label, zorder=3,
            )

    axes[1].legend(
        ncol=4, loc="upper right", fontsize=8
    )
    axes[1].set(
        ylabel=recording.metadata["units"],
        title=f"Filtered, polarity-oriented ECG — {summary['delineation_method']}",
        xlim=(t[0], end),
    )

    if len(rr):
        axes[2].plot(
            rr_end[accepted], 60 / rr[accepted],
            "o-", ms=4, label="Within configured range",
        )
        if np.any(~accepted):
            axes[2].scatter(
                rr_end[~accepted], 60 / rr[~accepted],
                marker="x", label="Outside range",
            )
        axes[2].legend()

    hr = summary["median_hr_bpm"]
    hr_label = "unavailable" if hr is None else f"{hr:.1f} bpm"
    if len(rr) and np.ptp(60 / rr) < 10:
        middle = float(np.median(60 / rr))
        axes[2].set_ylim(middle - 5, middle + 5)
    axes[2].set(
        ylabel="Estimated bpm",
        title=f"RR-derived heart rate — median {hr_label}",
    )

    if not len(rr):
        axes[2].text(
            0.5, 0.5,
            "No RR estimate: fewer than two R candidates detected",
            transform=axes[2].transAxes,
            ha="center", va="center",
        )
        axes[2].set_xlim(float(t[0]), float(t[-1]))
        axes[2].set_yticks([])

    for ax in axes:
        ax.set_xlabel("Time (s)")
        ax.grid(alpha=0.25)

    fig.savefig(folder / "ecg_analysis.png", dpi=150)
    if args.show:
        plt.show()
    plt.close(fig)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--version", action="version",
                        version=f"ECG lab {SCRIPT_VERSION}")
    parser.add_argument("--mode", choices=["demo", "mcp3008", "file"],
                        required=True)
    parser.add_argument("--fs", type=float, default=800,
                        help="Requested Hz; hardware rate is quantized to pigpio us.")
    parser.add_argument("--duration", type=float, default=10)
    parser.add_argument("--bpm", type=float, default=72)
    parser.add_argument("--channel", type=int, default=1)
    parser.add_argument("--vref", type=float, default=3.3)
    parser.add_argument("--input", type=Path)
    parser.add_argument("--units", default="unknown input units")
    parser.add_argument("--out", type=Path, default=Path("results"))
    parser.add_argument("--show", action="store_true")
    parser.add_argument("--polarity",
                        choices=["auto", "positive", "negative"],
                        default="auto")
    parser.add_argument("--lowcut", type=float, default=0.5)
    parser.add_argument("--highcut", type=float, default=40)
    parser.add_argument("--min-hr", type=float, default=35)
    parser.add_argument("--max-hr", type=float, default=180)
    parser.add_argument("--r-prominence", type=float)
    parser.add_argument("--plot-seconds", type=float, default=10)
    args = parser.parse_args(argv)

    for name in [
        "fs", "duration", "bpm", "vref", "lowcut", "highcut",
        "min_hr", "max_hr", "plot_seconds",
    ]:
        value = getattr(args, name)
        if not math.isfinite(value) or value <= 0:
            parser.error(f"--{name.replace('_', '-')} must be finite and positive")

    if not 100 <= args.fs <= 2000:
        parser.error("--fs must be between 100 and 2000 Hz.")
    if not 3 <= args.duration <= 600:
        parser.error("--duration must be between 3 and 600 seconds.")
    if not 0 <= args.channel <= 7 or not 0 < args.vref <= 3.3:
        parser.error("--channel must be 0..7 and --vref must be 0..3.3 V.")
    if not args.lowcut < args.highcut or not args.min_hr < args.max_hr:
        parser.error("Lower filter/HR bounds must be below upper bounds.")
    if args.r_prominence is not None and (
        not math.isfinite(args.r_prominence) or args.r_prominence <= 0
    ):
        parser.error("--r-prominence must be finite and positive.")
    if args.mode == "file" and args.input is None:
        parser.error("--mode file requires --input.")
    if args.mode == "demo" and not 40 <= args.bpm <= 140:
        parser.error("--bpm must be 40..140 for the simple demo morphology.")
    return args


def main(argv=None):
    args = parse_args(argv)
    run_name = (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S_%fZ")
        + "_" + args.mode
    )
    folder = args.out / run_name
    folder.mkdir(parents=True, exist_ok=False)

    print(f"ECG lab {SCRIPT_VERSION} | mode: {args.mode}", flush=True)
    print(f"Output: {folder.resolve()}")

    try:
        if args.mode == "demo":
            recording = demo(args.fs, args.duration, args.bpm)
            print("SIMULATED DATA: offline; this does not test Pi timing.")
        elif args.mode == "mcp3008":
            recording = acquire(args, folder)
        else:
            recording = load_recording(args.input, args.units)

        # Acquisition writes raw data immediately; this repeats the v2 save
        # contract for demo/file modes and guarantees raw data precedes analysis.
        save_raw(recording, folder)

        recording.metadata.update(
            script_version=SCRIPT_VERSION,
            created_utc=datetime.now(timezone.utc).isoformat(),
            python=platform.python_version(),
            numpy=np.__version__,
            scipy=scipy.__version__,
            options={
                k: str(v) if isinstance(v, Path) else v
                for k, v in vars(args).items()
            },
        )
        write_json(folder / "metadata.json", recording.metadata)

        summary = analyse(recording, folder, args)
        print(
            f"Samples: {len(recording.signal)}; "
            f"measured average rate: "
            f"{summary['timing']['measured_average_fs_hz']:.3f} Hz"
        )
        hr = summary["median_hr_bpm"]
        print(
            "Median estimated HR: "
            + ("unavailable" if hr is None else f"{hr:.1f} bpm")
        )
        print(
            f"R candidates: {summary['r_candidates']} | "
            f"delineation: {summary['delineation_method']}"
        )
        for warning in summary["warnings"]:
            print("NOTE:", warning)

    except (ValueError, RuntimeError, OSError, ImportError) as error:
        print(
            f"Stopped: {error}\nAny already saved raw data remains in {folder}",
            file=sys.stderr,
        )
        write_json(
            folder / "error.json",
            {"error": str(error), "analysis_completed": False},
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
