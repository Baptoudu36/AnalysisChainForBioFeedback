#!/usr/bin/env python3
"""
ECG lab acquisition and PQRST analysis.

Merged design:
  - MCP3008 sampling clock is generated by pigpio DMA, not Python sleep().
  - ADC samples are decoded from the pigpio GPIO notification stream.
  - Raw output/file layout is compatible with ecg_lab_v2.py.
  - R peaks use the conservative, inspectable SciPy detector from v2.
  - If NeuroKit2 is installed, DWT delineation supplies P/Q/S/T peaks and
    wave boundaries; otherwise v2-style local extrema are used as fallback.

Examples
--------
Demo:
  python3 ecg_lab_merged.py --mode demo --show

Pi / MCP3008:
  sudo pigpiod -s 1
  python3 ecg_lab_merged.py --mode mcp3008 --channel 1 --vref 3.3 --fs 800 --duration 30 --show
      

Reanalyse:
  python3 ecg_lab_merged.py --mode file --input results/YOUR_RUN/raw.csv --show

Outputs per run:
  raw.csv, raw.npz, metadata.json, filtered.csv,
  pqrst_candidates.csv, rr_intervals.csv, analysis.json, ecg_analysis.png
"""

